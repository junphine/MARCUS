from __future__ import annotations

import logging
import os
import re
from fastapi import APIRouter, HTTPException, status

from app.config import (
    SEGMENTS_DIR,
    QWENPAW_AGENT_ID,
    QWENPAW_BASE_URL,
    QWENPAW_PASSWORD,
    QWENPAW_USERNAME,
)
from app.modules.qwenpaw_remote_client import QwenPawRemoteClient
from app.schemas.chat import ChatRequest, ChatResponse
from app.schemas.healthcheck import HealthCheck

logger = logging.getLogger(__name__)
system_prompt = "你是一个文档问答助手。请仅在用户提供的工作区读写文件，你当前要处理的文档是%s。如果文档中不包含答案，请明确说明，不要编造。"
system_markdown_prompt = "你是一个文档问答助手。请仅根据用户提供的Markdown文档内容（在<document>中）回答问题。如果文档中不包含答案，请明确说明，不要编造。"

router = APIRouter(
    prefix="/chat",
    tags=["chat"],
    dependencies=[],
    responses={
        200: {"description": "OK"},
        400: {"description": "Bad Request"},
        500: {"description": "Internal Server Error"},
        502: {"description": "Bad Gateway"},
    },
)


@router.get("/", include_in_schema=False)
@router.get(
    "/health",
    tags=["healthcheck"],
    summary="Perform a Health Check on Chat Module",
    response_description="Return HTTP Status Code 200 (OK)",
    status_code=status.HTTP_200_OK,
    include_in_schema=False,
    response_model=HealthCheck,
)
def get_health() -> HealthCheck:
    """Perform a Health Check on the chat module."""
    return HealthCheck(status="OK")


def _resolve_document_dir(pdf_filename: str | None) -> str:
    """Resolve the working directory of the current document.

    Uploaded PDFs are stored directly in ``PDF_DIR``. When a filename is
    provided and the file exists, the directory containing it is returned.
    Otherwise ``PDF_DIR`` itself is used as the working directory.

    Args:
        pdf_filename: Sanitized filename of the current PDF (may be None).

    Returns:
        str: Absolute path of the document's directory.
    """
    if pdf_filename:
        # Strip any path components to prevent path traversal
        original_filename = pdf_filename

        # Directory layout (shared with the decimer segmentation flow):
        #   uploads/segments/{pdf_stem}/{pdf_stem}.md
        #   uploads/segments/{pdf_stem}/images/picture_N_segmented.png
        # Use the same directory naming as the segmentation router
        seg_safe_name = re.sub(r"[^\w.-]", "_", original_filename)
        pdf_stem = os.path.splitext(seg_safe_name)[0]
        segments_dir = os.path.join(SEGMENTS_DIR, pdf_stem)
        if os.path.isdir(segments_dir):
            return segments_dir,f"{pdf_stem}.md"
        logger.warning(
            "Chat requested for unknown document '%s', falling back to PDF_DIR",
            segments_dir,
        )
    return None,None


@router.post(
    "/ask",
    summary="Ask a question about the current document",
    response_description="Return the answer generated by the QwenPaw agent",
    status_code=status.HTTP_200_OK,
    response_model=ChatResponse,
)
def ask_question(request: ChatRequest) -> ChatResponse:
    """Answer a user question about the current document via QwenPaw.

    The directory containing the current document is passed to QwenPaw as
    the session project directory (``save_to_path``), so the agent can work
    with the document files when answering.

    Args:
        request: The chat request containing the question, the current
            PDF filename and an optional chat session identifier.

    Returns:
        ChatResponse: The generated answer.
    """
    question = request.question.strip()
    if not question:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Question must not be empty",
        )

    document_dir,md_file = _resolve_document_dir(request.pdf_filename)
    logger.info(
        "Chat question received (document dir: %s, session: %s)",
        document_dir,
        request.session_id,
    )

    try:
        client = QwenPawRemoteClient(
            base_url=QWENPAW_BASE_URL,
            agent_id=QWENPAW_AGENT_ID,
            username=QWENPAW_USERNAME,
            password=QWENPAW_PASSWORD,
        )

        # "Only send path" (default): pass only the question and let the
        # agent resolve the document files from the workspace path. When the
        # option is disabled (or no document is loaded), send the document's
        # markdown content (text and images) directly via ``ask_markdown``.
        if request.only_path or not document_dir:
            result = client.prompt(
                content=[{"type": "text", "text": question}],
                workspace=document_dir,
                system_prompt=[{"type": "text", "text": system_prompt % md_file}],
                session_id=request.session_id,
            )
        else:
            result = client.ask_markdown(
                prompt=[{"type": "text", "text": question}],
                system_prompt=[{"type": "text", "text": system_markdown_prompt}],
                directory=document_dir+os.path.sep+md_file,
                session_id=request.session_id,
            )
    except Exception as e:
        logger.exception("Failed to reach QwenPaw agent")
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=f"Failed to reach QwenPaw agent: {str(e)}",
        )

    if not result.get("success"):
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=result.get("error") or "QwenPaw agent returned an error",
        )

    # ``ask_markdown`` returns a single string when there is one document, but
    # a list of per-file results when there are several. Normalize to a string
    # so the response model stays valid.
    answer = result.get("content", "")
    if not isinstance(answer, str):
        answer = "\n\n".join(
            str(item.get("content", ""))
            for item in answer
            if isinstance(item, dict)
        )

    return ChatResponse(
        answer=answer,
        session_id=request.session_id,
        document_dir=document_dir,
    )
